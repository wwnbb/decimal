func TestDecimal_QuoRound_error(t *testing.T) {
	tests := []struct {
		d, e  string
		scale int
		mode  RoundingMode
		want  error
	}{
		{"1", "0", 2, HalfEven, ErrDivisionByZero},
		{"0", "0", 2, HalfEven, ErrDivisionByZero},
		{"1", "0.000", 2, Floor, ErrDivisionByZero},
		{"1", "3", 2, RoundingMode(6), ErrInvalidMode},
		{"1", "3", 2, RoundingMode(255), ErrInvalidMode},
		{"9999999999999999999", "0.1", 0, HalfEven, ErrOverflow},
		{"9999999999999999999", "0.5", 3, Down, ErrOverflow},
		{"-9999999999999999999", "0.5", 3, Down, ErrOverflow},
		{"9999999999999999999", "0.0000000000000000001", 0, Down, ErrOverflow},
		{"1", "0.0000000000000000001", 0, Down, ErrOverflow},
	}
	for _, tt := range tests {
		d, e := MustParse(tt.d), MustParse(tt.e)
		_, err := d.QuoRound(e, tt.scale, tt.mode)
		if !errors.Is(err, tt.want) {
			t.Errorf("%q.QuoRound(%q, %v, %v) error = %v, want %v", d, e, tt.scale, tt.mode, err, tt.want)
		}
	}
}

func TestMinMax(t *testing.T) {
	tests := []struct{ a, b, wantMin, wantMax string }{
		{"1", "2", "1", "2"},
		{"2", "1", "1", "2"},
		{"-1", "1", "-1", "1"},
		{"-2", "-1", "-2", "-1"},
		{"1.50", "1.5", "1.50", "1.50"}, // equal: the first argument
		{"1.5", "1.50", "1.5", "1.5"},
		{"0", "-0.0", "0", "0"},
		{"0.9999999999999999999", "9999999999999999999", "0.9999999999999999999", "9999999999999999999"},
	}
	for _, tt := range tests {
		a, b := MustParse(tt.a), MustParse(tt.b)
		if got, want := Min(a, b), MustParse(tt.wantMin); got != want {
			t.Errorf("Min(%q, %q) = %q, want %q", a, b, got, want)
		}
		if got, want := Max(a, b), MustParse(tt.wantMax); got != want {
			t.Errorf("Max(%q, %q) = %q, want %q", a, b, got, want)
		}
	}
}
